package org.example.blackjack.model.enums;

/**
 * Карты с их названиями.
 *
 * Каждая карта хранит значение очков, которые дает в игре.
 */
public enum Rank {
    /**
     * Карта "два", дает 2 очка.
     */
    TWO(2),
    /**
     * Карта "три", дает 3 очка.
     */
    THREE(3),
    /**
     * Карта "четыре", дает 4 очка.
     */
    FOUR(4),
    /**
     * Карта "пять", дает 5 очков.
     */
    FIVE(5),
    /**
     * Карта "шесть", дает 6 очков.
     */
    SIX(6),
    /**
     * Карта "семь", дает 7 очков.
     */
    SEVEN(7),
    /**
     * Карта "восемь", дает 8 очков.
     */
    EIGHT(8),
    /**
     * Карта "девять", дает 9 очков.
     */
    NINE(9),
    /**
     * Карта "десять", дает 10 очков.
     */
    TEN(10),
    /**
     * Карта "валет", дает 10 очков.
     */
    JACK(10),
    /**
     * Карта "дама", дает 10 очков.
     */
    QUEEN(10),
    /**
     * Карта "король", дает 10 очков.
     */
    KING(10),
    /**
     * Карта "Туз", дает 11 очков(в игре может дать 1 очко).
     */
    ACE(11);

    private final int value;

    Rank(int value){
        this.value = value;
    }

    /**
     * Возвращает базовое значение карты.
     * @return значение данной карты
     */
    public int getValue(){
        return value;
    }
}
