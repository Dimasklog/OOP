package org.example.blackjack.model.enums;

/**
 * Фазы раздачи блэкджека.
 * Некоторые фазы могут пропускаться в зависимости от ситуации.
 */
public enum RoundPhase {

    /**
     * Прием ставок игроков.
     */
    BETTING,

    /**
     * Выдача начальных карт игрокам и дилеру.
     */
    INITIAL_DEAL,

    /**
     * Предложение страховки при открытом тузе дилера.
     */
    INSURANCE,

    /**
     * Выполнение действий игроков по очереди.
     */
    PLAYER_TURNS,

    /**
     * Добор карт дилером по правилам стола.
     */
    DEALER_TURN,

    /**
     * Определение результатов рук и начисление выплат.
     */
    SETTLEMENT,

    /**
     * Раздача завершена, все результаты рассчитаны.
     */
    FINISHED
}